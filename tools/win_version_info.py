"""Write the Windows VS_VERSIONINFO resource text for ser2net.exe (ser2netweb.spec).

PyInstaller stamps the executable with the version resource this prints, built from the
single source of truth ser2netweb.__version__ (so the exe's Details tab, and anything that reads
its version, stay in step with the release). Pure standard library — it emits the plain
PyInstaller version-info format (a VSVersionInfo(...) expression), so it runs with the
build interpreter on Windows and needs no image or signing tooling.

    python3 tools/win_version_info.py build/win_version.txt
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

COMPANY = "Halis KILIÇ"
DESCRIPTION = "ser2net — serial-to-network bridge with a web UI"
PRODUCT = "ser2net"
ORIGINAL_FILENAME = "ser2net.exe"


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """'2.8.0' -> (2, 8, 0, 0); a trailing non-numeric part (e.g. '2.8.0rc1') is dropped."""
    parts: list[int] = []
    for piece in version.split(".")[:4]:
        digits = ""
        for ch in piece:
            if ch.isdigit():
                digits += ch
            else:
                break
        parts.append(int(digits) if digits else 0)
    while len(parts) < 4:
        parts.append(0)
    return parts[0], parts[1], parts[2], parts[3]


def render(version: str, year: int = 2026) -> str:
    vt = version_tuple(version)
    copyright_ = (f"Copyright (C) {year} {COMPANY}. "
                  "GNU AGPL-3.0-only or a commercial license.")
    strings = [
        ("CompanyName", COMPANY),
        ("FileDescription", DESCRIPTION),
        ("FileVersion", ".".join(str(n) for n in vt)),
        ("InternalName", PRODUCT),
        ("LegalCopyright", copyright_),
        ("OriginalFilename", ORIGINAL_FILENAME),
        ("ProductName", PRODUCT),
        ("ProductVersion", version),
    ]
    rows = ",\n            ".join(f"StringStruct({name!r}, {val!r})" for name, val in strings)
    # 040904B0 = U.S. English (0x0409), Unicode code page (0x04B0 = 1200)
    return f"""# Auto-generated by tools/win_version_info.py from ser2netweb.__version__ — do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vt},
    prodvers={vt},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [
            {rows}
        ])
    ]),
    VarFileInfo([VarStruct('Translation', [0x409, 1200])])
  ]
)
"""


def main(argv: list[str]) -> int:
    sys.path.insert(0, ROOT)
    from ser2netweb import __version__

    out = argv[0] if argv else os.path.join(ROOT, "build", "win_version.txt")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(__version__))
    print(f"wrote {out} (ser2net {__version__})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
